package io.github.bookshelf.feature.catalogs

import io.github.bookshelf.core.data.model.OpdsEntry

/**
 * Уровень браузера каталога: записи, их подпись и адрес фида.
 *
 * Хранится целиком, чтобы возврат на уровень выше не делал сетевой запрос: иначе «Назад»
 * выглядела бы как зависание — пользователь ждал бы фид, который уже был загружен.
 */
data class FeedLevel(
    val entries: List<OpdsEntry>,
    val feed: FeedUi,
    val feedUrl: String?,
    /** Ссылка `rel="next"` уровня: возврат обязан вернуть и возможность догрузки. */
    val nextUrl: String? = null,
)

/**
 * Стек открытых разделов каталога (docs/opds.md §3).
 *
 * Дефект, ради которого он появился (сообщение Александра, 28.09.2026): «Назад» в браузере
 * каталога всегда уводила к списку каталогов, то есть из вложенной категории нельзя было вернуться
 * на одну категорию назад — только выйти из каталога целиком. Теперь «Назад» снимает один уровень
 * со стека, а в корне каталога (стек пуст) возвращает к списку каталогов.
 */
class FeedBackStack {

    private val levels = ArrayDeque<FeedLevel>()

    /** Есть ли куда вернуться внутри каталога. */
    val canGoBack: Boolean get() = levels.isNotEmpty()

    /** Сколько уровней открыто — для проверок и подписи. */
    val size: Int get() = levels.size

    /** Запомнить текущий уровень перед переходом в раздел. */
    fun push(level: FeedLevel) {
        levels.addLast(level)
    }

    /** Снять последний уровень; `null`, если стек пуст (мы в корне каталога). */
    fun pop(): FeedLevel? = levels.removeLastOrNull()

    /** Новый каталог начинается с чистого стека: чужие разделы в истории недопустимы. */
    fun clear() {
        levels.clear()
    }
}
