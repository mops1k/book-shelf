package io.github.bookshelf.core.update.install

/**
 * Что делать перед запуском системного установщика (ADR-018).
 *
 * Начиная с Android 8 приложение обязано получить разрешение «установка неизвестных приложений»
 * для своего пакета — иначе установщик откажет, и для пользователя это выглядит как «скачал, а
 * ничего не произошло».
 */
enum class InstallGate {

    /** Можно открывать установщик. */
    ALLOWED,

    /** Сначала показать экран разрешения для нашего пакета. */
    REQUEST_PERMISSION,
}
