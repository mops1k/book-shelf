package io.github.bookshelf.core.metadata.rar

import io.github.bookshelf.core.metadata.parser.BookInput
import java.io.InputStream

/**
 * Одна запись RAR-архива: имя как в архиве и заявленный размер до распаковки.
 *
 * @param name имя с путём внутри архива; настоящие CBR собирают на Windows, поэтому разделителем
 *   встречается и обратный слэш.
 * @param sizeBytes размер распакованной записи; `-1`, если архив его не сообщает.
 */
data class RarEntry(
    val name: String,
    val sizeBytes: Long,
)

/**
 * У файла нет произвольного чтения.
 *
 * Облачный `DocumentsProvider` отдаёт pipe, а RAR без произвольного доступа не распаковать:
 * это не «битый архив», и книга не должна становиться `FAILED` — метаданные берутся из имени
 * файла, обложки не будет ([io.github.bookshelf.core.metadata.parser.ParseResult.Partial]).
 */
class RarNotSeekableException : Exception("у файла нет произвольного чтения")

/**
 * Чтение RAR-архива — порт, а не библиотека.
 *
 * Единственная библиотека для RAR (`com.github.junrar:junrar`) распространяется под несвободной
 * UnRar License, которую не принимает F-Droid, поэтому она подключается только во flavor `full`
 * (ADR-007). `:core:metadata` о сборках не знает: парсер комикса получает набор реализаций этого
 * порта, а в сборке без библиотеки набор пуст, и формат честно не предлагается.
 *
 * Соответствие «какая реализация» задаётся DI: во flavor `full` в набор попадает реализация
 * поверх junrar, в остальных сборках — ни одной.
 */
interface RarArchive {

    /**
     * Обойти записи в порядке архива, отдав каждую посетителю.
     *
     * Содержимое приходит ФУНКЦИЕЙ, а не готовым потоком, и это не украшение: junrar распаковывает
     * запись асинхронно (в фоновом потоке в pipe) и ошибку распаковки молча проглатывает. Если
     * открыть потоки для всех записей сразу, распаковки начнут конкурировать за один канал —
     * и запись, до которой посетитель дошёл позже, придёт пустой (так `ComicInfo.xml` терялся
     * на устройстве, хотя в списке записей он был). Поэтому поток создаётся тогда, когда
     * посетитель действительно собрался читать запись, и функция вызывается не более одного раза.
     *
     * Каждый обход начинается с начала архива, поэтому разбор может делать несколько проходов
     * (метаданные и обложка читаются отдельно).
     *
     * @throws RarNotSeekableException у книги нет произвольного чтения;
     * @throws Exception архив не читается (битый, зашифрованный, многотомный).
     */
    fun forEachEntry(input: BookInput, action: (RarEntry, () -> InputStream) -> Unit)
}
