package io.github.bookshelf.core.eink.frontlight

/**
 * Управление подсветкой e-ink экрана («Архитектура» §6, «E-ink UX» §1).
 *
 * Подсветка есть не у всех устройств, а у части — только холодная, у части — ещё и тёплая.
 * Поэтому контракт разделён: сначала [supportsFrontLight], и только потом установка уровня.
 * Отсутствие подсветки — штатное состояние, а не ошибка: приложение просто не показывает виджет.
 *
 * Реализация для Onyx (холодная и тёплая подсветка) появится вместе с `OnyxEinkController`
 * в Sprint 10; до этого используется no-op реализация.
 *
 * STUB(Sprint 10): реализация через вендорский API (Onyx SDK) + тёплая подсветка;
 *  `level()` возвращает `null`, если прошивка не отдаёт текущее значение.
 */
interface FrontLightController {

    fun supportsFrontLight(): Boolean

    /** Уровень 0..100; вне диапазона — значение обрезается реализацией. */
    fun setLevel(percent: Int)

    /** Текущий уровень 0..100 или `null`, если недоступен. */
    fun level(): Int?

    /**
     * Тёплая составляющая подсветки 0..100.
     *
     * Метод опционален: устройств с тёплой подсветкой меньшинство, поэтому по умолчанию — no-op,
     * а не обязательный к реализации контракт.
     */
    fun setWarmth(percent: Int) = Unit
}
