package io.github.bookshelf.core.eink.device

/**
 * Тип экрана устройства.
 *
 * Нужен отдельно от [io.github.bookshelf.core.eink.vendor.EinkVendor]: вендор отвечает на вопрос
 * «кто производитель и какие команды обновления доступны», а тип экрана — «что вообще перед
 * человеком». Пока эти два вопроса были склеены, устройство с электронной бумагой и без
 * вендорского контроллера выглядело обычным телефоном, и диагностика врала.
 *
 * Текст для человека выбирает экран приложения: у core-модуля нет ресурсов, а готовая русская
 * строка из ядра оставалась русской и в английском интерфейсе (дефект 01.10.2026). Ядро отвечает
 * только на вопрос «какой экран», а слова берутся из `R.string.settings_screen_*`.
 */
enum class EinkScreen {
    /** Обычный экран: телефон, планшет, эмулятор. */
    NORMAL,

    /** Цветная электронная бумага (Kaleido и подобные): есть признак цвета. */
    EINK_COLOR,

    /**
     * Чёрно-белая электронная бумага.
     *
     * Отдельного признака «чёрно-белая» в прошивках нет — есть только признак цвета. Поэтому так
     * помечается случай «вендор известен, признаков цвета не нашлось»: это самый частый случай, но
     * у вендора цветная модель без нашего признака показалась бы здесь. Список признаков цвета
     * расширяется по мере проверки на живых устройствах, а не по догадкам.
     */
    EINK_MONOCHROME,

    /**
     * Похоже на электронную бумагу, но вендор не опознан.
     *
     * Так помечаются устройства, где есть вендорские признаки электронной бумаги (`xrz`, `eink`,
     * `epd`), но имени производителя в них нет: обещать «чёрно-белая» тут было бы выдумкой.
     */
    EINK_UNKNOWN,
}
