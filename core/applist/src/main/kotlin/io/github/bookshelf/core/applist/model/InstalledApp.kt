package io.github.bookshelf.core.applist.model

import android.content.Intent

/**
 * Установленное приложение с launcher-активностью (ADR-015).
 *
 * Только то, что нужно списку: имя пакета, активность запуска, подпись и версия. Избранное,
 * скрытость и счётчик запусков живут в хранилище лаунчера (`LauncherStore`), а не здесь: каталог
 * описывает устройство, а предпочтения пользователя — отдельный слой. Смешав их, мы получили бы
 * модель, которую нельзя переиспользовать при повторном чтении без хранилища.
 */
data class InstalledApp(
    val packageName: String,
    /** Имя activity, которую надо запускать. Именно активность, а не класс Application. */
    val activityName: String,
    /** Подпись, как её показывает система (локализованная). */
    val label: String,
    /** `versionCode` нужен ключу иконки: после обновления приложения картинка меняется. */
    val versionCode: Long,
    /** Системное приложение: по умолчанию скрыто, показывается галочкой в «Лаунчере». */
    val isSystem: Boolean,
)

/** Порт каталога установленных приложений: единственная зависимость UI от Android-списка. */
interface AppCatalog {

    /** Имя собственного пакета: список приложений исключает сам BookShelf. */
    val ownPackage: String

    /** Приложения с активностью MAIN/LAUNCHER, включая системные: фильтры — дело правил списка. */
    suspend fun apps(): List<InstalledApp>

    /**
     * Интент запуска приложения.
     *
     * `null` — запустить нельзя (приложение удалили или его активность отключена): экран покажет
     * баннер, а не упадёт с `ActivityNotFoundException`.
     */
    fun launchIntent(app: InstalledApp): Intent?
}
