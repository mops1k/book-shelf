package io.github.bookshelf.core.common.error

/**
 * Почему файл книги не разобрался.
 *
 * Код, а не строка («TDD» §8): причина живёт в базе (`books.parseFailure`) и переживает
 * перезапуск, а слова выбирает экран — у слоя данных нет ресурсов, и готовый русский текст в
 * английском интерфейсе был бы непереводимым. Подробный текст парсера остаётся диагностикой в
 * `books.parseError` и в интерфейс не выводится (правило 7).
 */
enum class ParseFailure {

    /** Формат не поддержан: парсера для него нет. */
    FORMAT_UNSUPPORTED,

    /** Файл повреждён или не соответствует заявленному формату. */
    CORRUPT_FILE,

    /** Файл пустой. */
    EMPTY_FILE,

    /** Архив превысил допустимые размеры (защита от «бомбы»). */
    ARCHIVE_LIMIT,

    /**
     * Причина не опознана: так помечаются записи, которых нет в справочнике, и неожиданные отказы.
     * Карточка покажет общую формулировку, а не пустоту.
     */
    UNKNOWN,
}
