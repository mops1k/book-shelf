package io.github.bookshelf.core.common.app

import io.github.bookshelf.core.common.error.AppResult

/**
 * Открыть папку книги в системном файловом менеджере.
 *
 * Портом, а не вызовом из ViewModel: запуск `Intent` требует контекста и знания о SAF, а карточка
 * книги должна оставаться проверяемой тестом. Реализация живёт в `:app` — рядом с манифестом и
 * другими системными действиями (`AppRestarter`).
 */
fun interface FolderOpener {

    /**
     * Открыть папку, в которой лежит документ SAF.
     *
     * @return ошибка с понятной причиной, если адрес папки не вычислить или в системе нет
     *   программы, умеющей открывать папки. Молчаливого «ничего не произошло» здесь быть не должно:
     *   человек нажал кнопку.
     */
    fun openFolder(documentUri: String): AppResult<Unit>
}
