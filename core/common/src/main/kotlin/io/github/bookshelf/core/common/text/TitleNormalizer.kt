package io.github.bookshelf.core.common.text

/**
 * Приведение названия к виду, по которому сортируют библиотеки.
 *
 * Не «красивость», а практика: в реальных библиотеках половина книг начинается с «А», «The»,
 * «Над пропастью…», и без нормализации сортировка по названию бесполезна.
 *
 * Правила (реализуются в Спринте 4):
 * * срезать ведущие артикли и предлоги: `The `, `A `, `An `, `А `, `Над `, `Под `, `Из `;
 * * убрать ведущие кавычки и скобки;
 * * `Ё` → `Е` только для сравнения, не для отображения;
 * * регистр не менять — сортировка идёт через `COLLATE NOCASE` на стороне SQLite.
 */
interface TitleNormalizer {

    /** Возвращает строку для сортировки; для пустого/пробельного названия — пустая строка. */
    fun sortTitleOf(title: String, language: String? = null): String
}

/**
 * Реализация по умолчанию.
 *
 * STUB(Sprint 4): сейчас возвращает название без изменений, чтобы сортировка уже работала
 * и тесты на неё можно было написать первыми (red → green → refactor).
 */
class PassthroughTitleNormalizer : TitleNormalizer {

    override fun sortTitleOf(title: String, language: String?): String = title.trim()
}
