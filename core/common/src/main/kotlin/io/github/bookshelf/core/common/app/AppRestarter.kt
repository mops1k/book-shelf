package io.github.bookshelf.core.common.app

/**
 * Перезапуск приложения.
 *
 * Нужен там, где продолжать работу в текущем процессе нельзя: после восстановления базы файл
 * подменён, а открытые соединения и кэши держат прежние данные. Портом, а не вызовом
 * `Runtime.exit` прямо из экрана: экран должен уметь проверить, что перезапуск запрошен, не убивая
 * тестовый процесс.
 */
fun interface AppRestarter {

    /** Запросить перезапуск: текущий процесс завершится, приложение откроется заново. */
    fun restart()
}
