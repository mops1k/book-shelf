package io.github.bookshelf.core.common.io

import java.io.Closeable
import java.nio.channels.FileChannel

/**
 * Канал с произвольным доступом вместе с владельцем дескриптора.
 *
 * Зачем отдельный тип (находка аудита 28.09.2026): `ParcelFileDescriptor` — не простая обёртка над
 * числом. Когда объект собирает сборщик мусора, его финализатор закрывает файловый дескриптор.
 * Пока канал жив, а ссылка на дескриптор потеряна (так было в `DefaultBookContentOpener`),
 * сборщик мусора вправе закрыть файл прямо под работающим чтением — и разбор падал бы «на ровном
 * месте», тем реже, чем меньше памяти у устройства.
 *
 * Поэтому дескриптор держится рядом с каналом и освобождается вместе с ним, а вызывающий закрывает
 * один объект, а не помнит про два.
 */
class SeekableFile(
    val channel: FileChannel,
    private val owner: Closeable,
) : Closeable {

    /**
     * Закрыть канал и дескриптор.
     *
     * Оба закрытия не падают наружу: вызывающий освобождает ресурс в `finally`, и вторая ошибка
     * там была бы шумом. Повторный вызов тоже безопасен.
     */
    override fun close() {
        runCatching { channel.close() }
        runCatching { owner.close() }
    }
}
