package io.github.bookshelf.core.common.error

/**
 * Почему загрузка книги из OPDS не удалась.
 *
 * Код, а не готовая строка («TDD» §8): причина переживает перезапуск в
 * `opds_downloads.failure`, а слова выбирает экран — у слоя данных нет ресурсов. Подробный текст
 * (код ответа сервера, отказ провайдера) остаётся диагностикой в `opds_downloads.error` и уходит в
 * журнал: показывать его нельзя, иначе английский интерфейс показывал бы русские строки нижнего
 * слоя (правило 7).
 *
 * Живёт рядом с [AppError] и [ParseFailure] в `:core:common`, чтобы перевод мог жить в
 * `:core:designsystem`, а запись — в воркере приложения.
 */
enum class DownloadFailure {

    /**
     * Нет права записи в папку-получатель.
     *
     * Единственный отказ, который стоит слов: человек может его исправить, выбрав папку заново.
     */
    NO_WRITE_PERMISSION,

    /** Папка-получатель пропала: источник удалили или отозвали право. */
    RECEIVER_FOLDER_GONE,

    /** Пароль закрытого каталога не прочитался. */
    CREDENTIALS_UNREADABLE,

    /** Провайдер вернул адрес, из которого не собрать идентификатор книги. */
    BAD_DOCUMENT_URI,

    /** Загрузка не удалась по причине, которая человеку ничего не даёт (сеть, код ответа). */
    DOWNLOAD_FAILED,

    /** Причина не опознана: так помечаются записи, которых нет в справочнике. */
    UNKNOWN,
}
