package io.github.bookshelf.core.common.reader

/**
 * Открыта ли сейчас читалка.
 *
 * Зачем отдельная сущность: на слабом устройстве фоновая работа нашего приложения (обход дерева,
 * разбор метаданных, уборка кэша, поиск дублей) отбирает процессор и память у читалки, и её главный
 * поток встаёт — человек видит «FBReader не отвечает» почти на каждом перелистывании. Подтверждение
 * из системного журнала 30.09.2026: в ANR читалки наш процесс жёг 21% CPU, а её главный поток стоял
 * в `WaitingPerformingGc`.
 *
 * Поэтому тяжёлые работы спрашивают [isActive] и уступают: пока читалка открыта, мы не работаем, а
 * после возврата в приложение продолжаем с того же места.
 *
 * **Почему «читалка открыта» — это отметка, а не проверка чужого процесса.** Узнать чужое
 * приложение на экране без специальных разрешений нельзя (`getRunningAppProcesses` отдаёт только
 * свой процесс, `UsageStatsManager` требует отдельного доступа). Отметку ставит наш запуск читалки,
 * а снимает возврат в приложение — этого достаточно для сценария «открыл книгу из полки и читаю».
 */
interface ReaderSession {

    /**
     * Отметить, что книга открыта в читалке. Вызывается после успешного запуска.
     *
     * @param readerProfileId профиль читалки, которой книгу открыли (`fbreader`, `koreader`, …);
     *   `null`, если он неизвестен. По нему синхронизация прогресса понимает, **какую** читалку
     *   разрешено спрашивать, пока чтение идёт: состояние остальных в это время не разбирается
     *   (требование Александра, 05.10.2026).
     *
     * Не `suspend`: отметка — запись небольшого файла настроек, и ждать её нечего.
     */
    fun markOpened(bookId: String, readerProfileId: String?)

    /** Отметить книгу, когда профиль читалки не важен (тесты, старые вызовы). */
    fun markOpened(bookId: String) = markOpened(bookId, readerProfileId = null)

    /**
     * Что читается прямо сейчас; `null` — чтения нет.
     *
     * `null`, если отметки нет, если она устарела (приложение убили, читалку закрыли) или если наше
     * приложение само на экране: тогда фоновая работа никому не мешает.
     *
     * Обычная функция, а не `suspend`: читает небольшой файл настроек и вызывается из мест, где
     * корутины нет (проверка в цикле хеширования файлов).
     */
    fun active(): ActiveReading? = null

    /**
     * Идёт ли чтение прямо сейчас.
     *
     * Ответ по умолчанию выводится из [active]: у сессии один источник истины, и «есть ли чтение»
     * не может расходиться с «что именно читается».
     */
    fun isActive(): Boolean = active() != null

    /** Снять отметку: чтение закончилось. */
    fun clear()

    /** Наше приложение вышло на экран. */
    fun onAppForeground()

    /** Наше приложение ушло в фон. */
    fun onAppBackground()
}

/**
 * Что читается прямо сейчас.
 *
 * @param bookId наша книга, открытая в читалке: прогресс читается именно по ней, а не «по всей
 *   библиотеке» (требование Александра, 05.10.2026).
 * @param readerProfileId профиль читалки, которой книгу открыли; `null` — профиль неизвестен, и
 *   тогда источник по открытой читалке определить нельзя.
 */
data class ActiveReading(
    val bookId: String,
    val readerProfileId: String?,
)
