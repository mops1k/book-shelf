package io.github.bookshelf.core.storage.volume

import kotlinx.coroutines.flow.Flow

/**
 * Съёмные носители, подключённые к устройству сейчас.
 *
 * Поток обновляется при подключении и изъятии носителя: полка «Карта памяти» обязана появляться и
 * исчезать вместе с ним (требование Александра 01.10.2026). Пустой список означает «носителя нет».
 */
interface RemovableVolumeMonitor {

    /**
     * Наблюдение за подключёнными носителями.
     *
     * Поток отдаёт **список целиком** и первое значение — состояние на момент подписки: пустой
     * список должен быть виден так же явно, как непустой, иначе изъятие носителя не отличить от
     * «поток молчит».
     */
    fun observe(): Flow<List<RemovableVolume>>
}
