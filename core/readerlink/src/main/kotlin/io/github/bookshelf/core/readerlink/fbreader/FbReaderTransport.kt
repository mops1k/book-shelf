package io.github.bookshelf.core.readerlink.fbreader

/**
 * Транспорт к API-сервису FBReader: сырой вызов `request(code)` и ответ как есть.
 *
 * Отдельный порт, потому что в самом [FbReaderApi] лежат две разные вещи: привязка к чужому
 * сервису через `bindService` (Android, проверяется только на устройстве) и разбор ответов по
 * кодам (чистая логика, проверяется юнит-тестами). Здесь — граница между ними: транспорт знает
 * только «код → значение», а имена книг, названия и проценты собирает [DefaultFbReaderApi].
 *
 * Формат ответа снят с живого устройства (спайк 29.09.2026): сервис отвечает `success`, затем
 * тип значения, затем само значение. Транспорт уже разобрал это и отдал типизированное значение.
 */
interface FbReaderTransport {

    /**
     * Открыть сессию: привязаться к сервису с таймаутом.
     *
     * `false` — читалки нет, сервис не exported или не ответил: это обычная деградация, а не ошибка.
     * Сессия открывается на время синхронизации и закрывается [disconnect]: держать привязку
     * постоянно нельзя — она мешала бы системе выгружать читалку и ничего нам не даёт.
     */
    suspend fun connect(): Boolean

    /** true, если сессия открыта и binder жив. */
    fun isConnected(): Boolean

    /** Закрыть сессию; повторный вызов безопасен. */
    suspend fun disconnect()

    /**
     * Выполнить `request(code)` без аргументов.
     *
     * `null` означает «данных нет»: сервис недоступен, ответ не разобран или читалка ответила
     * значением неподходящего типа. Исключений наружу не выходит — недоступная читалка не должна
     * ронять синхронизацию.
     */
    suspend fun request(code: Int): FbReaderValue?
}

/**
 * Значение, которое вернул сервис.
 *
 * Типы повторяют ответы на те коды, которые нам нужны: строки (название, путь, язык), целое
 * (число абзацев) и позиция (абзац и элемент). Прочие типы ответа не разбираются — см.
 * [FbReaderValue.Unsupported].
 */
sealed interface FbReaderValue {

    /** Строка: может быть `null`, если читалка не знает значения (книга не открыта). */
    data class Text(val value: String?) : FbReaderValue

    /** Целое число: например, число абзацев. */
    data class Number(val value: Int) : FbReaderValue

    /** Позиция в тексте: абзац и элемент внутри него. */
    data class Position(val paragraphIndex: Int, val elementIndex: Int) : FbReaderValue

    /**
     * Ответ другого типа, чем мы ждали.
     *
     * Отдельный случай, а не «0» или пустая строка: если сервис сменил формат, лучше честно
     * остаться без данных, чем записать книге выдуманный прогресс.
     */
    data object Unsupported : FbReaderValue
}

/** Коды `ApiMethods` из FBReader: только те, что нужны синхронизации прогресса. */
object FbReaderCodes {

    /** `GET_BOOK_LANGUAGE` — язык открытой книги. */
    const val GET_BOOK_LANGUAGE = 501

    /** `GET_BOOK_TITLE` — название открытой книги. */
    const val GET_BOOK_TITLE = 502

    /** `GET_BOOK_FILE_PATH` — адрес открытой книги (для наших книг — их `documentUri`). */
    const val GET_BOOK_FILE_PATH = 505

    /** `GET_PARAGRAPHS_NUMBER` — сколько всего абзацев в книге. */
    const val GET_PARAGRAPHS_NUMBER = 601

    /** `GET_PAGE_START` — позиция, на которой открыта страница. */
    const val GET_PAGE_START = 701
}
