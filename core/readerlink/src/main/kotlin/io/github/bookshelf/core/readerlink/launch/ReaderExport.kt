package io.github.bookshelf.core.readerlink.launch

import android.net.Uri
import java.io.File
import io.github.bookshelf.core.common.error.AppResult

/**
 * Запасной способ отдать книгу читалке: копия файла и адрес, по которому её видно снаружи.
 *
 * Нужен читалкам, которые не открывают наш `content://` от SAF: одним подавай настоящий файл,
 * другим — адрес, выданный через FileProvider. Считается запасным путём, а не основным: копия
 * занимает место и её нужно убирать за собой.
 *
 * Порт объявлен здесь, а реализация живёт в `:core:data`: копирование требует доступа к файлам,
 * настроек и контекста, а лаунчеру достаточно «дай адрес копии» — так его поведение проверяется
 * тестом без файловой системы.
 */
interface ReaderExport {

    /**
     * Подготовить копию книги и вернуть её адрес для читалки.
     *
     * `Failure` означает, что запасного пути нет: экспорт выключен в настройках, файл больше лимита
     * копии или доступ к нему пропал. Причина попадает в текст ошибки — человек должен понять,
     * что именно случилось.
     *
     * @param extension расширение книги из [LaunchRequest]: попадает в имя копии. Без него
     *   читалка, которая определяет формат по имени файла, открывает свою последнюю книгу вместо
     *   выбранной (дефект из отчёта Александра 01.10.2026).
     */
    suspend fun exportedReaderUri(documentUri: String, extension: String): AppResult<Uri>
}

/**
 * Адрес файла, который увидит другая программа.
 *
 * Отдельным интерфейсом, потому что получение адреса требует Android-контекста и объявленного
 * `FileProvider`: без прослойки проверка самого экспорта упиралась бы в манифест тестового модуля,
 * а не в логику.
 */
fun interface ExportedUriFactory {

    /** Адрес файла для передачи наружу. */
    fun uriFor(file: File): Uri
}
