package io.github.bookshelf.core.readerlink.progress

/**
 * Книга, о прогрессе которой спрашивают читалку.
 *
 * Источники ищут книгу по-разному: FBReader называет её адресом, которым мы её отдали (`documentUri`),
 * KOReader — файлом рядом с книгой (`relativePath` внутри папки-источника), будущие CoolReader и
 * PocketBook — путём в своей базе. Поэтому в одном значении лежат все ключи, которые источникам
 * нужны, и ни один источник не вынужден сам ходить в чужое хранилище за именем файла.
 *
 * @param bookId идентификатор книги в нашей библиотеке; по нему пишется прогресс.
 * @param documentUri `content://`-адрес документа (или реальный путь для съёмного носителя).
 * @param readerAddress адрес, которым книга отдана читалке, **её** словами: читалка может читать
 *   копию внутри библиотеки или файл внутри архива (`zip-entry://`), и узнаёт она книгу именно по
 *   этому адресу. Для книг без копий совпадает с [documentUri].
 * @param fileName имя файла книги (`Солярис.fb2`) — ключ читалок, которые знают только его.
 * @param relativePath путь внутри папки-источника (`Лем/Солярис.fb2`).
 * @param sizeBytes размер файла: по нему различаются одинаковые имена в разных папках.
 * @param librarySourceId папка-источник книги; по ней источник находит дерево SAF.
 */
data class ProgressBookRef(
    val bookId: String,
    val documentUri: String,
    val readerAddress: String,
    val fileName: String,
    val relativePath: String,
    val sizeBytes: Long,
    val librarySourceId: String,
)

/**
 * Адрес книги, как его называет сама читалка.
 *
 * Это **не** наша книга: читалка может назвать копию, файл внутри архива (`zip-entry://`) или книгу
 * вообще не из нашей библиотеки. Опознание — отдельный шаг, поэтому здесь только то, что читалка
 * сказала, плюс подсказки для журнала.
 *
 * @param documentUri адрес документа в терминах читалки.
 * @param title название, если читалка его отдала: попадает в журнал, когда книга не нашлась.
 */
data class ReaderBookAddress(
    val documentUri: String,
    val title: String? = null,
)
