package io.github.bookshelf.core.readerlink.progress

/**
 * Чтение чужой базы данных читалки.
 *
 * Так хранят прогресс CoolReader (`/sdcard/.cr3/cr3db.sqlite`) и PocketBook
 * (`/sdcard/.pocketbook/books.db`): файл лежит на общей памяти, и его можно прочитать, если у
 * приложения есть доступ ко всей памяти (flavor `full`/`fdroid`; в `play` такого доступа нет).
 *
 * Почему порт, а не прямое обращение к SQLite: адаптеры читалок знают **схему** своих баз, но не
 * должны знать ни про копирование файлов, ни про `SQLiteDatabase` — это дело слоя данных. Порт
 * отдаёт минимум: открыть базу по пути и выполнить чтение.
 *
 * Обязанности реализации:
 * * копировать саму базу **вместе с журналами** (`-wal`, `-shm`, `-journal`) в кэш: у PocketBook WAL
 *   активен, и без него последние записи прогресса не видны;
 * * открывать копию **только для чтения** и никогда не менять файлы читалки;
 * * удалять копии при закрытии и возвращать `null`, если базы нет или она не читается.
 */
interface ProgressDatabase {

    /**
     * Открыть чужую базу для чтения; `null` — файла нет, он не читается или нет доступа.
     *
     * @param databasePath путь к файлу базы.
     */
    suspend fun open(databasePath: String): ProgressQuery?
}

/** Открытая чужая база: чтение строк и уборка копий. */
interface ProgressQuery : AutoCloseable {

    /**
     * Выполнить запрос на чтение.
     *
     * @param sql запрос с `?` вместо аргументов (подстановка только параметров, склейки SQL нет).
     * @param args значения аргументов.
     * @return строки как «колонка → значение»; значения строковые, `null` — NULL. Наружу исключения
     *   не выходят: непонятная схема означает «данных нет», а не сбой синхронизации.
     */
    fun rows(sql: String, args: List<String> = emptyList()): List<Map<String, String?>>

    /** Закрыть базу и убрать временные копии. Повторный вызов безопасен. */
    override fun close()
}
