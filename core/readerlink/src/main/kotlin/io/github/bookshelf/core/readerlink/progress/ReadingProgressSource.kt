package io.github.bookshelf.core.readerlink.progress

import io.github.bookshelf.core.common.error.AppResult

/**
 * Источник прогресса чтения — одна читалка (или один её способ хранить прогресс).
 *
 * Источники разные по природе, и это видно в контракте:
 * * **через API** (FBReader, AIDL) — читалка сама знает, что открыто сейчас, и отдаёт позицию только
 *   текущей книги: у неё есть [openedBook];
 * * **через файлы** (KOReader sidecar, CoolReader, PocketBook, Librera, XReader) — «что открыто
 *   сейчас» не знает никто, кроме нашей читательской сессии, а прогресс читается по конкретной
 *   книге: у таких источников [openedBook] возвращает `null`.
 *
 * Отсюда два режима обхода, которые различает сценарий синхронизации:
 * 1. **Во время чтения** читаем только тот источник, чья читалка открыта (её называет писательская
 *    сессия), и спрашиваем [progressFor] про конкретную книгу;
 * 2. **Фоновый проход** — по книгам, выбранным для чтения: у источников с [openedBook] спрашиваем
 *    один раз «что открыто», у файловых — по каждой книге.
 *
 * Привязка к чужому сервису — дело источника: [connect]/[disconnect] вызывают его же, поэтому
 * сценарий не может «забыть» закрыть чужой сервис.
 */
interface ReadingProgressSource {

    /** Канал прогресса: попадает в `reading_progress.source` и в диагностику. */
    val id: ProgressSourceId

    /**
     * Умеет ли источник сам назвать книгу, открытую сейчас.
     *
     * `true` у читалок с API (FBReader через AIDL): их спрашивают «что открыто», и этого достаточно.
     * `false` у файловых источников (KOReader sidecar, CoolReader, PocketBook, Librera, XReader):
     * «что открыто» не знает никто, кроме нашей читательской сессии, поэтому такие источники
     * читаются **по конкретной книге** — книге, выбранной для чтения.
     *
     * Признак нужен, чтобы фоновая работа не перебирала книги для читалки, которая и так знает
     * ответ: каждая лишняя привязка к чужому сервису — это работа на слабом устройстве.
     */
    val knowsOpenBook: Boolean

    /** Подготовиться к чтению; `false` — источник недоступен (читалки нет, API не отвечает). */
    suspend fun connect(): Boolean

    /** Освободить ресурсы. Вызывается всегда, даже если чтение упало; повторный вызов безопасен. */
    suspend fun disconnect()

    /** Что открыто в читалке сейчас; `null` — источник этого не знает или ничего не открыто. */
    suspend fun openedBook(): ReaderBookAddress?

    /**
     * Прогресс книги; `Failure`, если книга не найдена в состоянии читалки.
     *
     * Ноль процентов в этом случае возвращать нельзя: на полке это выглядело бы как «книга не
     * начата», хотя у источника просто нет данных.
     */
    suspend fun progressFor(book: ProgressBookRef): AppResult<ReadingProgressSnapshot>
}
