package io.github.bookshelf.core.readerlink.progress

/**
 * Чтение файлов, которые читалки кладут **рядом с книгой**.
 *
 * Так хранят прогресс файловые читалки: KOReader пишет `<книга>.sdr/metadata.<расширение>.lua`,
 * будущие источники — свои файлы рядом с книгой. Адресация «рядом с книгой» умеет разное: у книги
 * из папки SAF это документ внутри дерева, у книги со съёмного носителя — реальный путь. Знание об
 * этом живёт в реализации порта (`:core:data`), а адаптеры читалок работают с относительным путём —
 * поэтому в них нет ни `DocumentsContract`, ни работы с файловой системой.
 */
interface ProgressFileReader {

    /**
     * Прочитать текстовый файл рядом с книгой.
     *
     * @param book книга, чей соседний файл нужен.
     * @param sibling путь относительно папки книги, разделитель — `/`
     *   (например `Книга.fb2.sdr/metadata.epub.lua`).
     * @return содержимое файла или `null`, если файла нет или он не читается. Исключений не бросает:
     *   отсутствие файла — это «прогресса нет», а не сбой.
     */
    suspend fun readNearBook(book: ProgressBookRef, sibling: String): String?
}
