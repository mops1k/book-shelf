package io.github.bookshelf.core.readerlink.progress

/**
 * Чтение файлов читалки, которые лежат на общей памяти по **известному пути**.
 *
 * Отличие от [ProgressFileReader]: тот ищет файл рядом с книгой (sidecar KOReader), а здесь файл
 * живёт там, где его положила читалка: `/sdcard/Librera/profile.Librera/device.<модель>/app-Progress.json`.
 * Путь к нему из пути книги не выводится — каталог приходится сначала посмотреть ([children]), а имя
 * каталога зависит от модели устройства (`device.HiBreak`), поэтому его тоже нельзя зашить в код.
 *
 * Обязанности реализации: читать **только текст**, с ограничением объёма (чужой файл может быть
 * чем угодно), и возвращать «нет данных» вместо исключения, если файла нет или нет доступа ко всей
 * памяти (`full`/`fdroid` такой доступ есть, `play` — нет).
 */
interface ProgressStorage {

    /**
     * Прочитать текстовый файл.
     *
     * @param path реальный путь (не SAF-адрес).
     * @return текст файла; `null` — файла нет, это не файл или он не читается.
     */
    suspend fun read(path: String): String?

    /**
     * Перечислить содержимое каталога.
     *
     * @param directory реальный путь каталога.
     * @return имена файлов и вложенных каталогов; пусто — каталога нет или нет доступа.
     */
    suspend fun children(directory: String): List<String>
}
