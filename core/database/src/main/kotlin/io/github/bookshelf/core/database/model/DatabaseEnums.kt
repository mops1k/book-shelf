package io.github.bookshelf.core.database.model

/**
 * Перечисления модели данных, хранимые в БД как `TEXT` (имя константы).
 *
 * Все enum'ы конвертируются через `convert/Converters.kt`. Значения фиксированы: переименование
 * константы — это изменение схемы и требует миграции, потому что в SQLite лежит её имя.
 * См. `docs/architecture.md` §3.
 */

/**
 * Состояние разбора метаданных книги.
 *
 * Ошибка разбора — это состояние записи, а не исключение наружу: библиотека «никогда не падает
 * на битом файле» (docs/architecture.md §1).
 */
enum class ParseState {
    /** Файл найден, метаданные ещё не разобраны. */
    PENDING,

    /** Метаданные разобраны полностью. */
    OK,

    /** Разобрана часть метаданных: заголовок есть, обложки/полей может не быть. */
    PARTIAL,

    /** Разбор завершился ошибкой; текст ошибки лежит в `parseError`. */
    FAILED,

    /** Формат не поддерживается сборкой (например, DJVU/CB7). */
    UNSUPPORTED,
}

/** Источник, из которого получены метаданные книги. */
enum class MetadataSource {
    /** Метаданные извлечены из самого файла (FB2/EPUB/PDF/...). */
    EMBEDDED,

    /** Метаданные разобраны из имени файла. */
    FILENAME,

    /** Поля отредактированы пользователем вручную; парсер их не перезаписывает. */
    MANUAL,

    /** Метаданных нет: доступен только факт наличия файла. */
    NONE,
}

/** Статус чтения книги. */
enum class ReadingStatus {
    /** Не начата. */
    UNREAD,

    /** Читается. */
    READING,

    /** Дочитана. */
    READ,
}

/** Тип источника библиотеки. */
enum class SourceKind {
    /** Дерево, выбранное через `ACTION_OPEN_DOCUMENT_TREE` (SAF). */
    SAF_TREE,

    /** Прямой путь в файловой системе; только flavor `full`. */
    DIRECT_PATH,

    /** Источник, наполняемый загрузками OPDS. */
    OPDS,
}

/** Тип коллекции (полки). */
enum class CollectionType {
    /** Ручная полка: состав задаёт пользователь. */
    MANUAL,

    /** Умная полка: состав вычисляется по JSON-правилам. */
    SMART,
}

/** Состояние запуска сканирования источника. */
enum class ScanRunStatus {
    /** Скан выполняется прямо сейчас. */
    RUNNING,

    /** Скан приостановлен и может быть продолжен с курсора. */
    PAUSED,

    /** Скан дошёл до конца. */
    COMPLETED,

    /** Скан отменён пользователем. */
    CANCELLED,

    /** Скан завершился ошибкой; текст лежит в `error`. */
    FAILED,
}

/** Состояние загрузки записи каталога OPDS. */
enum class OpdsDownloadState {
    /** Загрузка в очереди. */
    QUEUED,

    /** Загрузка выполняется. */
    RUNNING,

    /** Загрузка приостановлена и может быть продолжена. */
    PAUSED,

    /** Загрузка завершена, файл записан в библиотеку. */
    DONE,

    /** Загрузка завершилась ошибкой; текст лежит в `error`. */
    FAILED,

    /** Загрузка отменена пользователем. */
    CANCELLED,
}

/** Вид закладки. */
enum class BookmarkKind {
    /** Позиция в тексте без выделения. */
    POSITION,

    /** Выделенный фрагмент текста. */
    HIGHLIGHT,

    /** Заметка пользователя. */
    NOTE,
}
