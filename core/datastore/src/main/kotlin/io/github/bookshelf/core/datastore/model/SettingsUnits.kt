package io.github.bookshelf.core.datastore.model

/**
 * Мегабайты настройки → байты лимита на диске.
 *
 * Лимиты [LibrarySettings] хранятся в мегабайтах, потому что их выбирает человек: «200 МБ»
 * читается и в `preferences_pb`, и в экспорте настроек, а `209715200` — нет. Сравнивают же объём
 * потребители в байтах (`File.length()`, объём кэша): перевод делается здесь один раз, чтобы
 * «свой» множитель не разъехался между воркером уборки обложек и хранилищем временных копий.
 *
 * Отрицательное значение — это испорченная настройка, а не «без лимита»: она приводится к нулю.
 * «Минус бесконечность» означала бы «никогда не чистить», и кэш рос бы без границы — ровно то,
 * от чего лимит и защищает.
 */
fun megabytesToBytes(megabytes: Int): Long =
    megabytes.coerceAtLeast(0).toLong() * BYTES_PER_MEGABYTE

/** 1 МБ — это 1024 КиБ, как объём считает файловая система. */
const val BYTES_PER_MEGABYTE: Long = 1024L * 1024L
