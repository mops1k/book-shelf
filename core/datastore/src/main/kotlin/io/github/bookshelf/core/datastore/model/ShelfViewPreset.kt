package io.github.bookshelf.core.datastore.model

/**
 * Вид полки по умолчанию — как открывается библиотека (docs/eink-ux.md §6.2).
 *
 * Объединяет два измерения в один выбор, потому что для пользователя это одно решение
 * «чем смотреть библиотеку»: «Сетка» показывает книги плитками с обложками, «Авторы» и «Серии» —
 * обзор по категориям. Ровно эти три кнопки стоят в строке видов на главном экране, поэтому
 * настройка по умолчанию выбирается из того же перечня.
 *
 * Режимы «Список» и «Компактно» из перечня убраны по решению Александра (28.09.2026): они не нужны,
 * книги всегда показываются плитками, а искать нужную помогают авторы, серии и поиск.
 */
enum class ShelfViewPreset {
    GRID,
    AUTHORS,
    SERIES,
    ;

    /** Обзор по категориям (в отличие от показа книг плитками). */
    val isBrowse: Boolean get() = this == AUTHORS || this == SERIES
}
