package io.github.bookshelf.core.datastore

/**
 * Допустимые интервалы опроса читалки ради прогресса.
 *
 * Живёт рядом с настройкой, потому что нужны обеим сторонам: экран «Читалки» показывает варианты,
 * а планировщик по ним ставит следующую работу. Варианты начинаются с двух минут — быстрее не имеет
 * смысла даже для самого быстрого читателя, а чаще будить чужой сервис невежливо.
 *
 * Держать значение в настройках «как ввёл пользователь» нельзя: файл настроек могли править вручную
 * или он остался от другой версии, и тогда мы поставили бы работу с интервалом в ноль минут.
 */
object ProgressSyncInterval {

    /** Варианты в минутах, по возрастанию. */
    val CHOICES_MINUTES: List<Int> = listOf(2, 5, 10, 15)

    /**
     * Значение из настроек, приведённое к допустимому варианту.
     *
     * Незнакомое число (в том числе ноль и отрицательное) заменяется документированным умолчанием:
     * работать по «интервалу» в ноль минут нельзя, это был бы непрерывный опрос чужого сервиса.
     */
    fun minutesOrDefault(value: Int): Int = when (value) {
        in CHOICES_MINUTES -> value
        else -> SettingsKeys.Defaults.PROGRESS_SYNC_INTERVAL_MINUTES
    }
}
