package io.github.bookshelf.core.datastore.update

/**
 * Когда последний раз проверяли обновления (ADR-018).
 *
 * Отдельный файл, а не ключ в настройках: отметка служебная, и битое значение не должно уносить
 * тему, папки-источники и настройки лаунчера. Хранится только время последней проверки — сам
 * ответ GitHub не кэшируем: устаревшее «есть новая версия» хуже, чем отсутствие диалога.
 */
interface UpdateStore {

    /** Время последней проверки в миллисекундах эпохи; `null` — ещё не проверяли. */
    suspend fun lastCheckEpochMs(): Long?

    /** Запомнить, что проверка была в это время. */
    suspend fun markChecked(epochMs: Long)
}
