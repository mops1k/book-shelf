package io.github.bookshelf.core.fb2opt

/**
 * Общие шаблоны разбора FB2.
 *
 * Атрибуты блока `<binary>` — обычная строка (они ASCII), а сам блок ищется по байтам
 * ([Fb2Binaries]): превращать всю книгу в строку ради поиска картинок нельзя, это удваивает
 * занимаемую память.
 */
internal object Fb2Patterns {

    /** Идентификатор картинки: по нему на неё ссылаются из тела книги. */
    val ID = Regex("""id\s*=\s*["']([^"']+)["']""")

    /** Тип картинки в атрибутах блока. */
    val CONTENT_TYPE = Regex("""content-type\s*=\s*["']([^"']+)["']""")
}
