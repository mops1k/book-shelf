package io.github.bookshelf.core.data.sync

/**
 * Порт постановки сканирования в фоновую очередь.
 *
 * Реализация намеренно живёт в `:app`: там `WorkManager` и `ScanSourceWorker`, а `:core:data`
 * не имеет права зависеть от `:app`. Такой разрыв зависимостей позволяет проверять постановку
 * подставным фейком, не поднимая Android-инфраструктуру в тестах репозиториев.
 *
 * Повторный вызов [enqueueScan] с тем же `sourceId` обязан приводить к **той же** уникальной
 * работе, а не плодить дубликаты: политика `ExistingWorkPolicy` — ответственность реализации,
 * контракт репозиториев от неё не зависит.
 */
interface ScanScheduler {

    /** Поставить сканирование источника в очередь; повторный вызов не создаёт вторую работу. */
    suspend fun enqueueScan(sourceId: String)

    /**
     * Мягко отменить работу источника: уже сохранённый курсор должен остаться пригодным
     * для [ScanCoordinator.resume].
     */
    suspend fun cancelScan(sourceId: String)
}
