package io.github.bookshelf.core.data.sync

/**
 * Сколько раз WorkManager повторяет сбойный прогон скана.
 *
 * Три — компромисс: временный отказ (занятый провайдер, пропавшая сеть у дерева на SD-карте) успеет
 * пройти, а работа не уйдёт в многомесячный backoff.
 */
const val MAX_SCAN_ATTEMPTS = 3

/**
 * Просить ли WorkManager повторить прогон.
 *
 * Повторы нужны только для временных сбоев. Если просить их без предела, WorkManager уводит работу
 * в экспоненциальный backoff, а `ExistingWorkPolicy.KEEP` не даёт поставить новый скан по тому же
 * источнику: кнопка «Пересканировать» перестаёт действовать (проверено на устройстве 30.09.2026 —
 * `run_attempt_count = 10`, работа так и висела в ENQUEUED).
 *
 * Когда повторы исчерпаны, работа завершается успешно, а прогон остаётся `PAUSED` с сохранённым
 * курсором: его продолжит следующий скан (по расписанию или по кнопке). Так состояние честное —
 * в истории прогонов видно причину, — а очередь не блокируется.
 */
fun shouldRetryScan(runAttemptCount: Int): Boolean = runAttemptCount < MAX_SCAN_ATTEMPTS
