package io.github.bookshelf.core.data.backup

/**
 * Просьба пересмотреть расписание бэкапа базы.
 *
 * Как и у синхронизации прогресса: расписание живёт в `:app` (там WorkManager), а меняют его
 * настройки — экран в feature-модуле. Модуль настроек не может зависеть от приложения, поэтому
 * он говорит «расписание надо пересмотреть», а что делать решает реализация.
 */
interface DatabaseBackupSchedule {

    /** Пересмотреть расписание по текущим настройкам. */
    suspend fun review()
}
