package io.github.bookshelf.core.data.author

/**
 * Разбор авторов и набор авторов книги.
 *
 * Авторы хранятся строкой (`books.authorsText`), а обзор и фильтры работают с отдельными людьми и
 * их наборами. Раньше ключом служила вся строка, поэтому одни и те же соавторы в другом порядке
 * («A, B» и «B, A») показывались как разные авторы, а книга, где автор записан вторым, по нему не
 * находилась (дефект Александра, 29.09.2026).
 *
 * Решение: категория автора — это ТОЧНЫЙ набор авторов книги; порядок в наборе не важен, подпись
 * выводится по алфавиту, поэтому одна и та же пара всегда выглядит одинаково.
 */

/**
 * Разбирает строку авторов на отдельных авторов.
 *
 * Разделители — запятая и точка с запятой (парсеры пишут «, », OPDS может писать «;»). Порядок
 * сохраняется, пустые куски отбрасываются, повтор одного имени считается один раз (иначе
 * «Лев Толстой, Лев Толстой» дал бы набор с автором дважды).
 */
fun parseAuthors(text: String?): List<String> =
    text.orEmpty()
        .split(',', ';')
        .map { it.trim() }
        .filter { it.isNotEmpty() }
        .distinct()

/**
 * Ключ набора авторов: порядок не важен, поэтому имена сортируются.
 *
 * Служит для группировки книг по составу соавторов и для сравнения наборов между собой.
 */
fun authorSetKey(authors: List<String>): String = sortedForDisplay(authors).joinToString("|")

/** Подпись набора авторов для человека: имена по алфавиту через запятую. */
fun authorSetLabel(authors: List<String>): String = sortedForDisplay(authors).joinToString(", ")

/** Имена по алфавиту без учёта регистра: одна и та же группа должна выглядеть одинаково. */
private fun sortedForDisplay(authors: List<String>): List<String> =
    authors.sortedWith(String.CASE_INSENSITIVE_ORDER)
