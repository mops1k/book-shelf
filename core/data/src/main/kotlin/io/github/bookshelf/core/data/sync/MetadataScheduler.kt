package io.github.bookshelf.core.data.sync

/**
 * Постановка разбора метаданных в очередь (docs/architecture.md §4.4).
 *
 * Отдельный порт от [ScanScheduler], потому что у них разный ритм: скан уникален на источник и
 * заменяет предыдущий, а разбор идёт по одной книге и должен накопиться, когда книг видно
 * сразу много. Смешивать их в одном интерфейсе означало бы заставлять одного реализатора
 * думать о двух несвязанных политиках уникальности.
 */
interface MetadataScheduler {
    /** Поставить разбор одной книги; повторная постановка не должна дублировать работу. */
    /**
     * Поставить разбор книги.
     *
     * @param force разобрать заново даже при `parseState = OK` — для разового бэкфилла жанров.
     */
    suspend fun enqueueMetadata(bookId: String, force: Boolean = false)
}
