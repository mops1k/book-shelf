package io.github.bookshelf.core.data.model

import io.github.bookshelf.core.data.author.authorSetKey

/**
 * Категория обзора авторов — ТОЧНЫЙ набор авторов книги.
 *
 * Решение владельца (29.09.2026): «Александр Тарарев, Юрий Тарарев» и «Юрий Тарарев, Александр
 * Тарарев» — одна категория с общим числом книг, а книга с тремя авторами — отдельная категория.
 * Книга с одним автором даёт категорию «A», поэтому соавтор со своими книгами показывается
 * дополнительно отдельным автором.
 *
 * @param names имена набора по алфавиту — именно они уходят в фильтр запроса;
 * @param label подпись по алфавиту: одна и та же группа всегда выглядит одинаково;
 * @param count сколько книг попадает в категорию (и ровно столько откроется по клику).
 */
data class AuthorSet(
    val names: List<String>,
    val label: String,
    val count: Int,
) {

    /**
     * Ключ набора для UI — тот же, что строит `authorSetKey` в SQL: имена по алфавиту через «|».
     *
     * По нему категория обзора узнаётся среди строк списка и строится уровень обзора; обратный
     * разбор (`authorSetNames`) возвращает имена фильтру. Порядок имён на отбор не влияет —
     * он сравнивает состав авторов, а не строку.
     */
    val key: String get() = authorSetKey(names)
}
