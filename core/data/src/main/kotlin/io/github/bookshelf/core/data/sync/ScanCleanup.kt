package io.github.bookshelf.core.data.sync

/**
 * Какие книги источника можно удалить после прохода скана.
 *
 * Решение вынесено из воркера отдельной функцией, потому что ошибка в нём стоит библиотеки.
 * 30.09.2026 она и случилась: прогон скана ушёл в `PAUSED` (ошибка `UNIQUE books.documentUri`),
 * WorkManager повторил работу, а повтор **возобновил** прогон с середины дерева. Возобновлённый
 * проход видит только хвост дерева, поэтому список встреченных книг в нём неполный — и удаление
 * «всего, чего не видели» стёрло всю полку: 79 книг исчезли из базы (файлы остались на месте).
 *
 * Поэтому удаление разрешено только при **полном** проходе:
 * * [resumed] — прогон продолжали с курсора: встреченные книги неполные, удалять нельзя;
 * * [filesSeen] равно нулю — обход не нашёл ни одного файла. Пустая папка даёт то же самое, но
 *   сбой доступа выглядит так же, а цена ошибки разная: лишние строки дождутся следующего скана,
 *   удалённые данные — нет.
 *
 * @param allIds все книги источника по базе;
 * @param seenIds книги, встреченные в этом проходе;
 * @param filesSeen сколько файлов прошёл проход (счётчик воркера, а не размер [seenIds]: файл может
 *   быть пропущен фильтром форматов и не стать книгой).
 */
fun booksToDelete(
    allIds: List<String>,
    seenIds: Set<String>,
    filesSeen: Int,
    resumed: Boolean,
): List<String> = when {
    resumed -> emptyList()
    filesSeen <= 0 -> emptyList()
    else -> allIds.filterNot { id -> id in seenIds }
}
