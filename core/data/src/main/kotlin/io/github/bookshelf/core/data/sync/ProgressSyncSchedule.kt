package io.github.bookshelf.core.data.sync

/**
 * Просьба пересмотреть расписание синхронизации прогресса.
 *
 * Порт нужен потому, что расписание живёт в `:app` (там WorkManager), а меняют его настройки —
 * экран в `feature:settings`. Модуль настроек не может зависеть от приложения, поэтому он говорит
 * «расписание надо пересмотреть», а что именно делать (поставить цепочку, отменить её, сменить
 * интервал) решает реализация в `:app`.
 *
 * Вызывать после каждой записи настройки не нужно: достаточно тех случаев, когда меняется само
 * поведение синхронизации — включение, выключение и интервал.
 */
interface ProgressSyncSchedule {

    /** Пересмотреть расписание по текущим настройкам. */
    suspend fun review()
}
