package io.github.bookshelf.core.data.model

/**
 * Файл-копия книги, созданный не нами («Архитектура» §3.1).
 *
 * Копия книгой не считается: она не попадает на полку (иначе из-за копии читалки в библиотеке
 * появлялась вторая книга — 92 вместо 91, дефект 01.10.2026), а живёт связью с книгой и показывается
 * отдельным списком «Копии книг на устройстве»: файл занимает место, и человек должен решать, убирать
 * его или нет.
 *
 * @param copyDocumentUri адрес документа копии в дереве SAF.
 * @param bookId книга, которую копия повторяет; её прогресс чтения и статус — настоящие.
 * @param bookTitle название книги для списка: без него строка была бы безликим адресом.
 * @param sizeBytes размер файла копии.
 */
data class BookCopy(
    val copyDocumentUri: String,
    val bookId: String,
    val bookTitle: String,
    val sizeBytes: Long,
)
